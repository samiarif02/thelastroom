#!/usr/bin/env python3
"""Writes lib/src/phosphor_icons.dart: the Phosphor glyphs Daylight uses, as const IconData on
the fonts bundled in fonts/phosphor/ (the regular, bold and fill TTFs of @phosphor-icons/web,
MIT, LICENSE beside them). phosphor_flutter can't be used: it extends IconData, which is final
since Flutter 3.32.

Add a glyph by adding its Phosphor name (kebab case, https://phosphoricons.com) to NAMES, then
run from packages/brand:  python3 tool/phosphor_icons.py && dart format lib/src/phosphor_icons.dart
"""
import re
import urllib.request

VERSION = '2.1.1'
STYLES = {'regular': ('Regular', ''), 'bold': ('Bold', '-bold'), 'fill': ('Fill', '-fill')}
NAMES = sorted({
    'arrow-counter-clockwise', 'arrow-right', 'buildings', 'calendar-blank', 'cards', 'chart-bar',
    'check', 'check-circle', 'circle-half', 'copy-simple', 'door', 'ear', 'elevator', 'hand',
    'handshake', 'hash', 'lightbulb-filament', 'lightning', 'lock-simple', 'lock-simple-open',
    'magnifying-glass', 'medal', 'microphone', 'pause', 'play', 'push-pin', 'share-network',
    'stack', 'stop', 'timer', 'trend-up', 'user-circle', 'users-three', 'x',
    # WS2's screens (brief 46).
    'arrow-left', 'arrow-up', 'bell', 'book-open', 'caret-right', 'chat-circle', 'clock',
    'flag', 'gear-six', 'hourglass', 'microphone-slash', 'moon', 'notebook', 'sparkle',
    'speaker-high', 'target', 'trophy', 'warning-circle', 'waveform', 'wifi-slash',
})


def camel(name):
    head, *rest = name.split('-')
    return head + ''.join(p.capitalize() for p in rest)


def codepoints(style):
    url = f'https://unpkg.com/@phosphor-icons/web@{VERSION}/src/{style}/style.css'
    css = urllib.request.urlopen(url).read().decode()
    prefix = 'ph' if style == 'regular' else f'ph-{style}'
    found = dict(re.findall(r'\.' + re.escape(prefix) + r'\.ph-([a-z0-9-]+):before\s*{\s*content:\s*"\\([0-9a-f]+)"', css))
    return {n: found[n] for n in NAMES}


out = [
    '// Generated by tool/phosphor_icons.py from @phosphor-icons/web ' + VERSION + '. Do not edit.',
    "import 'package:flutter/widgets.dart' show IconData;",
    '',
]
for style, (title, _) in STYLES.items():
    points = codepoints(style)
    out += [
        f'/// Phosphor {style} glyphs (MIT; fonts/phosphor). Material icons are banned in Daylight.',
        f'abstract final class Phosphor{title} {{',
    ]
    for name in NAMES:
        out.append(
            f"  static const IconData {camel(name)} = IconData(0x{points[name]}, "
            f"fontFamily: 'Phosphor{title}', fontPackage: 'brand');"
        )
    out += ['}', '']
open('lib/src/phosphor_icons.dart', 'w').write('\n'.join(out))
