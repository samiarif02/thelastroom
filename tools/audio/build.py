"""Builds the game's whole sound library from `cues.py`. Run from the repo root:

    python3 tools/audio/build.py            # every cue
    python3 tools/audio/build.py stamp ...  # just these (credits still list every cue)

Per cue: synthesise (seeded, so reproducible) -> loudness-normalise to its target with a -1 dBTP
ceiling -> mono 44.1 kHz 16-bit WAV in tools/audio/build/ (not committed) -> OGG Vorbis (Android,
web) and M4A AAC (iOS) in apps/mobile/assets/audio/ -> a row in docs/audio-credits.md.

Needs numpy, ffmpeg (EBU R128 meter, AAC) and oggenc (`brew install vorbis-tools`).
"""

import json
import re
import subprocess
import sys
import wave
import zlib
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))

from cues import CUES, LOOP_SECONDS  # noqa: E402
from dsp import SR, fade, true_peak  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
BUILD = Path(__file__).parent / "build"
ASSETS = ROOT / "apps/mobile/assets/audio"
CREDITS = ROOT / "docs/audio-credits.md"

CEILING_DBTP = -1.0
ONE_SHOT_FADE_OUT = 0.12
OGG_QUALITY = {"effects": "3", "ambience": "1"}
AAC_BITRATE = {"effects": "64k", "ambience": "48k"}
# The R128 meter gates out silence, so padding a very short cue lets it be measured at all.
MEASURE_PAD_SECONDS = 1.0


def seed_for(name):
    return zlib.crc32(name.encode())


def write_wav(path, x, seed):
    r = np.random.default_rng(seed)
    dither = (r.uniform(-0.5, 0.5, len(x)) + r.uniform(-0.5, 0.5, len(x))) / 32767
    pcm = np.clip(np.round((x + dither) * 32767), -32768, 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def integrated_lufs(path):
    result = subprocess.run(
        [
            "ffmpeg", "-hide_banner", "-nostats", "-i", str(path),
            "-af", f"apad=pad_dur={MEASURE_PAD_SECONDS},ebur128",
            "-f", "null", "-",
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    summary = result.stderr.split("Summary:")[-1]
    return float(re.search(r"I:\s+(-?[\d.]+) LUFS", summary).group(1))


def render(spec):
    x = np.asarray(spec["fn"](np.random.default_rng(seed_for(spec["name"]))), dtype=float)
    x -= np.mean(x) if spec["loop"] else 0
    if not spec["loop"]:
        x = fade(x, 0, min(ONE_SHOT_FADE_OUT, len(x) / SR * 0.2))
    x /= np.max(np.abs(x)) + 1e-12
    raw = BUILD / f"{spec['name']}.raw.wav"
    write_wav(raw, x * 0.5, seed_for(spec["name"]))
    measured = integrated_lufs(raw) - 20 * np.log10(0.5)
    gain_db = spec["lufs"] - measured
    peak_db = 20 * np.log10(true_peak(x) + 1e-12) + gain_db
    limited = peak_db > CEILING_DBTP
    if limited:
        gain_db -= peak_db - CEILING_DBTP
    y = x * 10 ** (gain_db / 20)
    out = BUILD / f"{spec['name']}.wav"
    write_wav(out, y, seed_for(spec["name"]))
    raw.unlink()
    return out, integrated_lufs(out), bool(limited), len(y) / SR


def encode(spec, wav):
    name, bus = spec["name"], spec["bus"]
    ogg = ASSETS / "ogg" / f"{name}.ogg"
    m4a = ASSETS / "m4a" / f"{name}.m4a"
    subprocess.run(
        ["oggenc", "--quiet", "-q", OGG_QUALITY[bus], "--serial", str(seed_for(name) % 2**31),
         "--discard-comments", "-o", str(ogg), str(wav)],
        check=True,
    )
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", str(wav),
         "-c:a", "aac", "-b:a", AAC_BITRATE[bus], "-ac", "1",
         "-map_metadata", "-1", "-fflags", "+bitexact", "-flags:a", "+bitexact",
         str(m4a)],
        check=True,
    )
    return ogg, m4a


def write_credits(rows):
    lines = [
        "# Audio credits",
        "",
        "Every sound file the app ships, where it came from and its licence. Generated by",
        "`python3 tools/audio/build.py`; don't edit by hand (the build rewrites it).",
        "",
        "**Source of every file: original synthesis in this repo** (`tools/audio/cues.py`, one",
        "function per cue, built by `tools/audio/build.py`). No third-party recordings, samples or",
        "packs are used. Licence: **CC0 1.0** (public domain dedication,",
        "https://creativecommons.org/publicdomain/zero/1.0/), so the files can ship in the stores",
        "and be reused with no attribution.",
        "",
        "Edits, for every file: rendered mono 44.1 kHz, loudness-normalised to the target below",
        "(EBU R128 integrated, ffmpeg `ebur128`) with a -1 dBTP true-peak ceiling, then encoded to",
        "OGG Vorbis (`oggenc`) and M4A AAC (`ffmpeg`). A target marked *peak-limited* hit the",
        "ceiling first, so it sits a little under its target.",
        "",
        f"Loops (`loop`) are exactly {LOOP_SECONDS:g} s and periodic: they repeat with no seam.",
        "",
        "| File (`assets/audio/{ogg,m4a}/`) | Cue | What it is | Source | Licence | Edits |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        loudness = f"{row['lufs']:.1f} LUFS"
        if row["limited"]:
            loudness += " (peak-limited)"
        kind = "loop" if row["loop"] else f"{row['seconds']:.2f} s"
        lines.append(
            f"| `{row['name']}.ogg`, `{row['name']}.m4a` | `{row['name']}` | {row['describe']} "
            f"| synthesised, `tools/audio/cues.py` `{row['name']}()` | CC0 1.0 "
            f"| {row['bus']}, {kind}, {loudness} |"
        )
    CREDITS.write_text("\n".join(lines) + "\n")


def main(only):
    BUILD.mkdir(exist_ok=True)
    (ASSETS / "ogg").mkdir(parents=True, exist_ok=True)
    (ASSETS / "m4a").mkdir(parents=True, exist_ok=True)
    report_path = BUILD / "report.json"
    report = json.loads(report_path.read_text()) if report_path.exists() else {}
    for spec in CUES:
        if only and spec["name"] not in only:
            continue
        wav, lufs, limited, seconds = render(spec)
        ogg, m4a = encode(spec, wav)
        report[spec["name"]] = {
            "lufs": lufs, "limited": limited, "seconds": seconds,
            "ogg_bytes": ogg.stat().st_size, "m4a_bytes": m4a.stat().st_size,
        }
        print(f"{spec['name']:22} {seconds:5.2f}s {lufs:6.1f} LUFS{' limited' if limited else ''}"
              f"  ogg {ogg.stat().st_size // 1024:4d} KB  m4a {m4a.stat().st_size // 1024:4d} KB")
    report_path.write_text(json.dumps(report, indent=2))
    names = {spec["name"] for spec in CUES}
    rows = [{**spec, **report[spec["name"]]} for spec in CUES if spec["name"] in report]
    missing = names - set(report)
    if missing:
        sys.exit(f"not built yet: {sorted(missing)}; run without arguments once")
    write_credits(rows)
    total = sum(v["ogg_bytes"] + v["m4a_bytes"] for k, v in report.items() if k in names)
    print(f"total {total / 1024 / 1024:.2f} MB across {len(rows)} cues, both formats")


if __name__ == "__main__":
    main(set(sys.argv[1:]))
